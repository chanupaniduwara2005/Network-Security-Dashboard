"""SentinelSOC - Threat Detection Engine.

Implements rule-based security event correlation and anomaly detection across
normalized authentication and system event streams.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import Any, List, Optional, Sequence, Union

import pandas as pd

from src.severity import ConfidenceLevel, SeverityAssessment, SeverityEvaluator, SeverityLevel


@dataclass
class DetectionConfig:
    """Configurable thresholds and rules parameters for the detection engine."""

    # Rule 1: Repeated Failed Logins (Brute-Force pattern)
    failed_login_threshold: int = 5
    failed_login_window_minutes: int = 5

    # Rule 2: Distributed Login Failures (Multi-IP target or Spraying)
    distributed_ip_threshold: int = 3
    distributed_user_threshold: int = 3
    distributed_window_minutes: int = 10

    # Rule 3: Successful Login After Failures
    login_after_failures_threshold: int = 3
    login_after_failures_window_minutes: int = 15

    # Rule 4: Privileged Account Activity
    privileged_users: list[str] = field(
        default_factory=lambda: [
            "admin",
            "root",
            "administrator",
            "service_db",
            "service_backup",
            "security_admin",
            "steve.rogers",
        ]
    )
    sensitive_event_types: list[str] = field(
        default_factory=lambda: [
            "PRIVILEGE_ELEVATION",
            "CONFIG_CHANGE",
            "USER_MANAGEMENT",
            "SECURITY_POLICY",
        ]
    )

    # Rule 5: Suspicious Event Patterns
    off_hours_start_hour: int = 23  # 11:00 PM
    off_hours_end_hour: int = 5     # 05:00 AM
    flag_port_scans: bool = True


@dataclass
class Alert:
    """Represents a structured security alert generated by a detection rule."""

    alert_id: str
    rule_name: str
    severity: str  # CRITICAL, HIGH, MEDIUM, LOW, INFORMATIONAL
    username: Optional[str]
    source_ips: list[str]
    first_seen: str
    last_seen: str
    event_count: int
    related_event_ids: list[str]
    explanation: str
    recommended_steps: list[str]
    status: str = "NEW"  # Open, Investigating, False Positive, Resolved, NEW
    confidence: str = "MEDIUM"  # HIGH, MEDIUM, LOW
    severity_justification: list[str] = field(default_factory=list)
    analyst_notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        """Convert alert to dictionary for tabular display or serialization."""
        return {
            "alert_id": self.alert_id,
            "rule_name": self.rule_name,
            "severity": self.severity,
            "confidence": self.confidence,
            "username": self.username or "N/A",
            "source_ips": ", ".join(self.source_ips),
            "first_seen": self.first_seen,
            "last_seen": self.last_seen,
            "event_count": self.event_count,
            "related_event_ids": self.related_event_ids,
            "explanation": self.explanation,
            "severity_justification": " | ".join(self.severity_justification),
            "recommended_steps": " | ".join(self.recommended_steps),
            "status": self.status,
            "analyst_notes": self.analyst_notes,
        }


def _generate_alert_id(rule_code: str, entity: str, timestamp_str: str) -> str:
    """Generate a deterministic, stable alert ID using rule code, target, and time hash."""
    seed = f"{rule_code}_{entity}_{timestamp_str}"
    digest = hashlib.sha256(seed.encode("utf-8")).hexdigest()[:8].upper()
    return f"ALT-{rule_code}-{digest}"


def _format_timestamp(ts: Any) -> str:
    """Format timestamp consistently as ISO string."""
    if isinstance(ts, pd.Timestamp):
        return ts.strftime("%Y-%m-%d %H:%M:%SZ")
    if isinstance(ts, datetime):
        return ts.strftime("%Y-%m-%d %H:%M:%SZ")
    return str(ts)


class DetectionEngine:
    """Evaluates normalized events against correlation rules and emits structured alerts."""

    def __init__(self, config: Optional[DetectionConfig] = None, severity_evaluator: Optional[SeverityEvaluator] = None):
        self.config = config or DetectionConfig()
        self.severity_evaluator = severity_evaluator or SeverityEvaluator()

    def _prepare_events_df(self, events: Union[pd.DataFrame, list[dict[str, Any]]]) -> pd.DataFrame:
        """Ensure input events are formatted into a sorted DataFrame with UTC datetime timestamps."""
        if isinstance(events, list):
            if not events:
                return pd.DataFrame()
            df = pd.DataFrame(events)
        elif isinstance(events, pd.DataFrame):
            if events.empty:
                return pd.DataFrame()
            df = events.copy()
        else:
            return pd.DataFrame()

        if "timestamp" not in df.columns:
            return pd.DataFrame()

        if not pd.api.types.is_datetime64_any_dtype(df["timestamp"]):
            df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True, errors="coerce")

        df = df.dropna(subset=["timestamp"]).sort_values("timestamp").reset_index(drop=True)
        if "username" in df.columns:
            df["username"] = df["username"].fillna("UNKNOWN")
        if "status" in df.columns:
            df["status"] = df["status"].fillna("UNKNOWN")
        if "event_type" in df.columns:
            df["event_type"] = df["event_type"].fillna("UNKNOWN")
        if "source_ip" in df.columns:
            df["source_ip"] = df["source_ip"].fillna("UNKNOWN")

        return df

    def detect_all(self, events: Union[pd.DataFrame, list[dict[str, Any]]]) -> list[Alert]:
        """Run all configured detection rules against the provided events."""
        df = self._prepare_events_df(events)
        if df.empty:
            return []

        alerts: list[Alert] = []
        alerts.extend(self.detect_repeated_failed_logins(df))
        alerts.extend(self.detect_distributed_login_failures(df))
        alerts.extend(self.detect_login_after_failures(df))
        alerts.extend(self.detect_privileged_activity(df))
        alerts.extend(self.detect_suspicious_patterns(df))

        # Sort alerts by severity descending
        severity_order = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3, "INFORMATIONAL": 4}
        alerts.sort(key=lambda a: (severity_order.get(a.severity, 5), a.first_seen), reverse=False)

        return alerts

    def detect_repeated_failed_logins(self, events: Union[pd.DataFrame, list[dict[str, Any]]]) -> list[Alert]:
        """Rule 1: Detect 5 or more failed logins for the same user and IP in a time window."""
        df = self._prepare_events_df(events)
        if df.empty:
            return []

        alerts: list[Alert] = []
        threshold = self.config.failed_login_threshold
        window = timedelta(minutes=self.config.failed_login_window_minutes)

        # Filter failed logins
        failed_df = df[(df["status"] == "FAILED") & (df["event_type"].str.contains("LOGIN", na=False))]
        if failed_df.empty:
            return alerts

        # Group by username and source IP
        grouped = failed_df.groupby(["username", "source_ip"], observed=True)

        for (user, src_ip), group in grouped:
            user_str = str(user)
            ip_str = str(src_ip)
            group_sorted = group.sort_values("timestamp")
            records = group_sorted.to_dict(orient="records")

            # Sliding window algorithm
            n = len(records)
            i = 0
            while i < n:
                window_start = records[i]["timestamp"]
                window_events = [records[i]]
                j = i + 1
                while j < n and (records[j]["timestamp"] - window_start) <= window:
                    window_events.append(records[j])
                    j += 1

                if len(window_events) >= threshold:
                    first_ts = window_events[0]["timestamp"]
                    last_ts = window_events[-1]["timestamp"]
                    event_ids = [str(e["event_id"]) for e in window_events]

                    alert_id = _generate_alert_id("BRUTE", f"{user_str}_{ip_str}", str(first_ts))

                    assessment = self.severity_evaluator.evaluate(
                        rule_category="BRUTE",
                        event_count=len(window_events),
                        username=user_str,
                        source_ips=[ip_str],
                    )

                    alerts.append(
                        Alert(
                            alert_id=alert_id,
                            rule_name="Repeated Failed Logins (Potential Brute-Force)",
                            severity=assessment.level.value,
                            username=user_str,
                            source_ips=[ip_str],
                            first_seen=_format_timestamp(first_ts),
                            last_seen=_format_timestamp(last_ts),
                            event_count=len(window_events),
                            related_event_ids=event_ids,
                            explanation=(
                                f"Observed {len(window_events)} consecutive failed login attempts "
                                f"for user '{user_str}' from IP {ip_str} within "
                                f"{self.config.failed_login_window_minutes} minutes. "
                                "This pattern indicates possible automated password guessing or credential abuse."
                            ),
                            recommended_steps=[
                                "Inspect source IP reputation and ownership in threat intelligence databases.",
                                "Temporarily enforce rate-limiting or firewall block on source IP.",
                                "Check if the target account has been locked or was later accessed successfully.",
                                "Prompt the affected user to verify if this was user error or an external attack.",
                            ],
                            status="NEW",
                            confidence=assessment.confidence.value,
                            severity_justification=assessment.justification,
                        )
                    )
                    # Advance past this cluster to avoid duplicate alerts for the same burst
                    i = j
                else:
                    i += 1

        return alerts

    def detect_distributed_login_failures(self, events: Union[pd.DataFrame, list[dict[str, Any]]]) -> list[Alert]:
        """Rule 2: Detect distributed failed logins from multiple IPs targeting one user or spray from one IP."""
        df = self._prepare_events_df(events)
        if df.empty:
            return []

        alerts: list[Alert] = []
        window = timedelta(minutes=self.config.distributed_window_minutes)

        failed_df = df[(df["status"] == "FAILED") & (df["event_type"].str.contains("LOGIN", na=False))]
        if failed_df.empty:
            return alerts

        # Sub-rule 2A: Targeted user attacked from multiple distinct source IPs
        for user, group in failed_df.groupby("username", observed=True):
            user_str = str(user)
            group_sorted = group.sort_values("timestamp")
            records = group_sorted.to_dict(orient="records")

            n = len(records)
            i = 0
            while i < n:
                window_start = records[i]["timestamp"]
                window_events = [records[i]]
                j = i + 1
                while j < n and (records[j]["timestamp"] - window_start) <= window:
                    window_events.append(records[j])
                    j += 1

                distinct_ips = sorted(list({str(e["source_ip"]) for e in window_events if e.get("source_ip")}))

                if len(distinct_ips) >= self.config.distributed_ip_threshold:
                    first_ts = window_events[0]["timestamp"]
                    last_ts = window_events[-1]["timestamp"]
                    event_ids = [str(e["event_id"]) for e in window_events]

                    alert_id = _generate_alert_id("DIST-LOGIN", user_str, str(first_ts))

                    assessment = self.severity_evaluator.evaluate(
                        rule_category="DIST",
                        event_count=len(window_events),
                        username=user_str,
                        source_ips=distinct_ips,
                    )

                    alerts.append(
                        Alert(
                            alert_id=alert_id,
                            rule_name="Distributed Login Failures (Multi-Source)",
                            severity=assessment.level.value,
                            username=user_str,
                            source_ips=distinct_ips,
                            first_seen=_format_timestamp(first_ts),
                            last_seen=_format_timestamp(last_ts),
                            event_count=len(window_events),
                            related_event_ids=event_ids,
                            explanation=(
                                f"Observed failed login attempts against user '{user_str}' originating from "
                                f"{len(distinct_ips)} distinct IP addresses ({', '.join(distinct_ips)}) "
                                f"within {self.config.distributed_window_minutes} minutes. "
                                "This pattern is consistent with a distributed brute-force or botnet attack."
                            ),
                            recommended_steps=[
                                "Check if the source IPs originate from proxy networks, Tor exits, or VPNs.",
                                "Examine authentication logs across all affected endpoints.",
                                "Reset the credentials of the targeted account if necessary.",
                            ],
                            status="NEW",
                            confidence=assessment.confidence.value,
                            severity_justification=assessment.justification,
                        )
                    )
                    i = j
                else:
                    i += 1

        # Sub-rule 2B: Password Spraying (Single IP failing logins across multiple distinct usernames)
        for src_ip, group in failed_df.groupby("source_ip", observed=True):
            ip_str = str(src_ip)
            group_sorted = group.sort_values("timestamp")
            records = group_sorted.to_dict(orient="records")

            n = len(records)
            i = 0
            while i < n:
                window_start = records[i]["timestamp"]
                window_events = [records[i]]
                j = i + 1
                while j < n and (records[j]["timestamp"] - window_start) <= window:
                    window_events.append(records[j])
                    j += 1

                distinct_users = sorted(list({str(e["username"]) for e in window_events if e.get("username")}))

                if len(distinct_users) >= self.config.distributed_user_threshold:
                    first_ts = window_events[0]["timestamp"]
                    last_ts = window_events[-1]["timestamp"]
                    event_ids = [str(e["event_id"]) for e in window_events]

                    alert_id = _generate_alert_id("SPRAY", ip_str, str(first_ts))

                    assessment = self.severity_evaluator.evaluate(
                        rule_category="SPRAY",
                        event_count=len(window_events),
                        username="Multiple",
                        source_ips=[ip_str],
                    )

                    alerts.append(
                        Alert(
                            alert_id=alert_id,
                            rule_name="Password Spraying Pattern Detected",
                            severity=assessment.level.value,
                            username=f"Multiple ({len(distinct_users)} users)",
                            source_ips=[ip_str],
                            first_seen=_format_timestamp(first_ts),
                            last_seen=_format_timestamp(last_ts),
                            event_count=len(window_events),
                            related_event_ids=event_ids,
                            explanation=(
                                f"Source IP {ip_str} attempted logins across {len(distinct_users)} different "
                                f"user accounts within {self.config.distributed_window_minutes} minutes. "
                                "This matches horizontal password spraying behaviors used to evade single-account lockouts."
                            ),
                            recommended_steps=[
                                "Immediately block or challenge authentication attempts from this IP.",
                                "Review if any attempted username had a subsequent successful login.",
                                "Notify the SOC incident response lead of ongoing spraying activity.",
                            ],
                            status="NEW",
                            confidence=assessment.confidence.value,
                            severity_justification=assessment.justification,
                        )
                    )
                    i = j
                else:
                    i += 1

        return alerts

    def detect_login_after_failures(self, events: Union[pd.DataFrame, list[dict[str, Any]]]) -> list[Alert]:
        """Rule 3: Detect successful login after recent repeated failures for the same user."""
        df = self._prepare_events_df(events)
        if df.empty:
            return []

        alerts: list[Alert] = []
        threshold = self.config.login_after_failures_threshold
        window = timedelta(minutes=self.config.login_after_failures_window_minutes)

        auth_df = df[df["event_type"].str.contains("LOGIN", na=False)]
        if auth_df.empty:
            return alerts

        for user, group in auth_df.groupby("username", observed=True):
            user_str = str(user)
            group_sorted = group.sort_values("timestamp")
            records = group_sorted.to_dict(orient="records")

            for idx, event in enumerate(records):
                if event["status"] == "SUCCESS":
                    success_time = event["timestamp"]
                    # Look back within window for recent failures
                    recent_failures = [
                        r
                        for r in records[:idx]
                        if r["status"] == "FAILED"
                        and (success_time - r["timestamp"]) <= window
                    ]

                    if len(recent_failures) >= threshold:
                        related_ids = [str(r["event_id"]) for r in recent_failures] + [str(event["event_id"])]
                        all_ips = list(dict.fromkeys([str(r["source_ip"]) for r in recent_failures] + [str(event["source_ip"])]))

                        alert_id = _generate_alert_id("SUCCESS-AFTER-FAIL", user_str, str(event["timestamp"]))

                        assessment = self.severity_evaluator.evaluate(
                            rule_category="SUCCESS_AFTER_FAIL",
                            event_count=len(related_ids),
                            username=user_str,
                            source_ips=all_ips,
                            success_after_failures=True,
                        )

                        alerts.append(
                            Alert(
                                alert_id=alert_id,
                                rule_name="Successful Login After Multiple Failures",
                                severity=assessment.level.value,
                                username=user_str,
                                source_ips=all_ips,
                                first_seen=_format_timestamp(recent_failures[0]["timestamp"]),
                                last_seen=_format_timestamp(success_time),
                                event_count=len(related_ids),
                                related_event_ids=related_ids,
                                explanation=(
                                    f"User '{user_str}' experienced {len(recent_failures)} failed login attempts "
                                    f"followed by a successful login at {_format_timestamp(success_time)} from IP {event.get('source_ip')}. "
                                    "This pattern may represent a compromised account after successful brute-forcing or user password recovery."
                                ),
                                recommended_steps=[
                                    "Contact the user out-of-band (e.g. phone/Slack) to confirm legitimate access.",
                                    "Inspect session activity for anomalous file access or lateral movement.",
                                    "If unauthorized, immediately revoke active tokens and reset credentials.",
                                ],
                                status="NEW",
                                confidence=assessment.confidence.value,
                                severity_justification=assessment.justification,
                            )
                        )

        return alerts

    def detect_privileged_activity(self, events: Union[pd.DataFrame, list[dict[str, Any]]]) -> list[Alert]:
        """Rule 4: Detect privileged usernames performing sensitive event types."""
        df = self._prepare_events_df(events)
        if df.empty:
            return []

        alerts: list[Alert] = []
        priv_users_lower = {u.strip().lower() for u in self.config.privileged_users}
        sensitive_events_upper = {e.strip().upper() for e in self.config.sensitive_event_types}

        for _, row in df.iterrows():
            user = str(row.get("username", "")).strip().lower()
            event_type = str(row.get("event_type", "")).strip().upper()

            if user in priv_users_lower and event_type in sensitive_events_upper:
                ts = row["timestamp"]
                event_id = str(row.get("event_id", ""))
                src_ip = str(row.get("source_ip", "UNKNOWN"))

                alert_id = _generate_alert_id("PRIV-ACT", f"{user}_{event_type}", str(ts))

                assessment = self.severity_evaluator.evaluate(
                    rule_category="PRIV",
                    event_count=1,
                    username=user,
                    source_ips=[src_ip] if src_ip != "UNKNOWN" else [],
                )

                alerts.append(
                    Alert(
                        alert_id=alert_id,
                        rule_name="Privileged Account Sensitive Activity",
                        severity=assessment.level.value,
                        username=str(row.get("username")),
                        source_ips=[src_ip] if src_ip != "UNKNOWN" else [],
                        first_seen=_format_timestamp(ts),
                        last_seen=_format_timestamp(ts),
                        event_count=1,
                        related_event_ids=[event_id] if event_id else [],
                        explanation=(
                            f"Privileged account '{row.get('username')}' performed sensitive action '{event_type}' "
                            f"on host '{row.get('hostname', 'UNKNOWN')}'. "
                            "Notice: This rule is contextual audit monitoring and does not denote confirmed malice."
                        ),
                        recommended_steps=[
                            "Cross-reference timestamp with approved change management tickets.",
                            "Verify if the requesting administrator was on active duty.",
                            "Review command line arguments or authorization records.",
                        ],
                        status="NEW",
                        confidence=assessment.confidence.value,
                        severity_justification=assessment.justification,
                    )
                )

        return alerts

    def detect_suspicious_patterns(self, events: Union[pd.DataFrame, list[dict[str, Any]]]) -> list[Alert]:
        """Rule 5: Detect suspicious event categories like port scans or unusual off-hours logins."""
        df = self._prepare_events_df(events)
        if df.empty:
            return []

        alerts: list[Alert] = []

        for _, row in df.iterrows():
            event_type = str(row.get("event_type", "")).strip().upper()
            status = str(row.get("status", "")).strip().upper()
            ts = row["timestamp"]
            event_id = str(row.get("event_id", ""))
            src_ip = str(row.get("source_ip", "UNKNOWN"))
            user = str(row.get("username", "UNKNOWN"))

            # 5A: Explicit port scan or perimeter reconnaissance
            if self.config.flag_port_scans and ("PORT_SCAN" in event_type or "SCAN" in event_type):
                alert_id = _generate_alert_id("SCAN", src_ip, str(ts))
                assessment = self.severity_evaluator.evaluate(
                    rule_category="SCAN",
                    event_count=1,
                    username=user if user != "UNKNOWN" else None,
                    source_ips=[src_ip] if src_ip != "UNKNOWN" else [],
                )
                alerts.append(
                    Alert(
                        alert_id=alert_id,
                        rule_name="Network Reconnaissance (Port Scan)",
                        severity=assessment.level.value,
                        username=user if user != "UNKNOWN" else None,
                        source_ips=[src_ip] if src_ip != "UNKNOWN" else [],
                        first_seen=_format_timestamp(ts),
                        last_seen=_format_timestamp(ts),
                        event_count=1,
                        related_event_ids=[event_id] if event_id else [],
                        explanation=(
                            f"Reconnaissance event '{event_type}' detected from origin IP {src_ip}. "
                            "External probes indicate automated asset scanning or vulnerability discovery."
                        ),
                        recommended_steps=[
                            "Verify if the source IP is an authorized internal vulnerability scanner.",
                            "Inspect perimeter firewall drop rates for this IP address.",
                            "Block persistent scanners at edge routing access control lists (ACLs).",
                        ],
                        status="NEW",
                        confidence=assessment.confidence.value,
                        severity_justification=assessment.justification,
                    )
                )

            # 5B: Off-hours unauthenticated access attempts
            if isinstance(ts, (pd.Timestamp, datetime)):
                hour = ts.hour
                if (hour >= self.config.off_hours_start_hour or hour < self.config.off_hours_end_hour):
                    if status in {"FAILED", "BLOCKED"} and "LOGIN" in event_type:
                        alert_id = _generate_alert_id("OFFHOURS", f"{user}_{src_ip}", str(ts))
                        assessment = self.severity_evaluator.evaluate(
                            rule_category="OFFHOURS",
                            event_count=1,
                            username=user if user != "UNKNOWN" else None,
                            source_ips=[src_ip] if src_ip != "UNKNOWN" else [],
                            is_off_hours=True,
                        )
                        alerts.append(
                            Alert(
                                alert_id=alert_id,
                                rule_name="Suspicious Off-Hours Login Attempt",
                                severity=assessment.level.value,
                                username=user if user != "UNKNOWN" else None,
                                source_ips=[src_ip] if src_ip != "UNKNOWN" else [],
                                first_seen=_format_timestamp(ts),
                                last_seen=_format_timestamp(ts),
                                event_count=1,
                                related_event_ids=[event_id] if event_id else [],
                                explanation=(
                                    f"Failed or blocked login attempt for '{user}' occurred outside normal business hours "
                                    f"at {ts.strftime('%H:%M:%S UTC')} from IP {src_ip}."
                                ),
                                recommended_steps=[
                                    "Check if the user is in an alternate timezone or scheduled for on-call shift.",
                                    "Monitor for subsequent successful authentication from the same IP.",
                                ],
                                status="NEW",
                                confidence=assessment.confidence.value,
                                severity_justification=assessment.justification,
                            )
                        )

        return alerts
